#!/usr/bin/env node
// scripts/skills/sync-plugin-skills.mjs
//
// Mirrors the canonical agent skills in `skills/` into the Claude Code plugin
// payloads under `plugins/<plugin>/skills/`.
//
// Why a copy instead of a symlink or a marketplace-root `source: "./"`:
//   - `check-tracked-artifacts` forbids tracked symlinks (mode 120000), and a
//     symlink would break anyway once Claude Code copies the plugin into
//     `~/.claude/plugins/cache`.
//   - A marketplace entry with `source: "./"` would copy the whole 217 MB repo
//     into that cache, once per plugin and per version.
// So `skills/` stays the single source of truth (it is generated by
// `scripts/skills/generate-agent-skills.mjs`) and this script republishes it
// into the small, self-contained plugin directories.
//
// Usage:
//   node scripts/skills/sync-plugin-skills.mjs            # write (sync)
//   node scripts/skills/sync-plugin-skills.mjs --check    # verify only, exit 1 on drift

import fs from "node:fs";
import path from "node:path";
import { fileURLToPath, pathToFileURL } from "node:url";

const __filename = fileURLToPath(import.meta.url);
const REPO_ROOT = path.resolve(path.dirname(__filename), "..", "..");

const SOURCE_DIR = path.join(REPO_ROOT, "skills");
const PLUGINS_DIR = path.join(REPO_ROOT, "plugins");
const PACKAGE_JSON = path.join(REPO_ROOT, "package.json");

/**
 * Plugin versions track the package version so a release ships the updated
 * skills: Claude Code pins an installed plugin to its manifest `version` and
 * only pulls a new copy when that string changes.
 *
 * @param {string} [packageJsonPath]
 * @returns {string}
 */
export function readPackageVersion(packageJsonPath = PACKAGE_JSON) {
  return JSON.parse(fs.readFileSync(packageJsonPath, "utf8")).version;
}

/**
 * Routing table: which plugin payload each skill id belongs to.
 * Order matters — the first matching rule wins.
 */
export const PLUGIN_ROUTES = [
  { plugin: "omniroute-cli", match: (id) => id.startsWith("cli-") || id === "config-codex-cli" },
  { plugin: "omniroute-api", match: (id) => id.startsWith("omni-") },
];

/**
 * Resolves the plugin that owns a skill id.
 *
 * @param {string} id - skill directory name (e.g. "omni-providers")
 * @returns {string|null} plugin name, or null when no rule matches
 */
export function resolvePlugin(id) {
  for (const route of PLUGIN_ROUTES) {
    if (route.match(id)) return route.plugin;
  }
  return null;
}

/**
 * Lists the canonical skill ids: every directory under `skills/` holding a SKILL.md.
 *
 * @param {string} [sourceDir]
 * @returns {string[]} sorted skill ids
 */
export function listSkillIds(sourceDir = SOURCE_DIR) {
  return fs
    .readdirSync(sourceDir, { withFileTypes: true })
    .filter((entry) => entry.isDirectory())
    .map((entry) => entry.name)
    .filter((id) => fs.existsSync(path.join(sourceDir, id, "SKILL.md")))
    .sort();
}

/**
 * Lists every `plugins/<name>/.claude-plugin/plugin.json` in the tree.
 *
 * @param {string} [pluginsDir]
 * @returns {string[]} absolute manifest paths, sorted by plugin name
 */
export function listPluginManifests(pluginsDir = PLUGINS_DIR) {
  if (!fs.existsSync(pluginsDir)) return [];
  return fs
    .readdirSync(pluginsDir, { withFileTypes: true })
    .filter((entry) => entry.isDirectory())
    .map((entry) => path.join(pluginsDir, entry.name, ".claude-plugin", "plugin.json"))
    .filter((manifestPath) => fs.existsSync(manifestPath))
    .sort();
}

/**
 * Snapshots a directory tree as a relative-path -> file-content map.
 * Returns an empty map when the directory does not exist.
 *
 * @param {string} dir
 * @returns {Map<string, string>}
 */
function snapshot(dir) {
  /** @type {Map<string, string>} */
  const files = new Map();
  if (!fs.existsSync(dir)) return files;

  const walk = (current) => {
    for (const entry of fs.readdirSync(current, { withFileTypes: true })) {
      const abs = path.join(current, entry.name);
      if (entry.isDirectory()) {
        walk(abs);
      } else if (entry.isFile()) {
        files.set(path.relative(dir, abs).split(path.sep).join("/"), fs.readFileSync(abs, "utf8"));
      }
    }
  };

  walk(dir);
  return files;
}

/**
 * Rewrites the `"version"` field of a plugin manifest in place.
 *
 * Surgical string replacement rather than parse/re-serialize: `JSON.stringify`
 * would re-wrap arrays that Prettier keeps inline, so every sync would fight
 * lint-staged over formatting.
 *
 * @param {string} manifestSource - raw plugin.json contents
 * @param {string} version
 * @returns {string} rewritten contents
 */
export function stampVersion(manifestSource, version) {
  return manifestSource.replace(/("version":\s*")[^"]*(")/, `$1${version}$2`);
}

/**
 * Reads the declared `version` of a plugin manifest.
 *
 * @param {string} manifestSource - raw plugin.json contents
 * @returns {string|null} the declared version, or null when the field is absent
 */
export function readManifestVersion(manifestSource) {
  const parsed = JSON.parse(manifestSource);
  return typeof parsed.version === "string" ? parsed.version : null;
}

/**
 * Computes the drift between `skills/` and the plugin payloads.
 *
 * @param {object} [options]
 * @param {string} [options.sourceDir]
 * @param {string} [options.pluginsDir]
 * @param {string} [options.version] - expected plugin manifest version
 * @returns {{ unrouted: string[], drift: string[], byPlugin: Map<string, string[]> }}
 */
export function planSync({
  sourceDir = SOURCE_DIR,
  pluginsDir = PLUGINS_DIR,
  version = readPackageVersion(),
} = {}) {
  /** @type {string[]} */
  const unrouted = [];
  /** @type {string[]} */
  const drift = [];
  /** @type {Map<string, string[]>} */
  const byPlugin = new Map();

  for (const id of listSkillIds(sourceDir)) {
    const plugin = resolvePlugin(id);
    if (!plugin) {
      unrouted.push(id);
      continue;
    }
    if (!byPlugin.has(plugin)) byPlugin.set(plugin, []);
    byPlugin.get(plugin).push(id);
  }

  for (const [plugin, ids] of byPlugin) {
    const targetRoot = path.join(pluginsDir, plugin, "skills");

    for (const id of ids) {
      const expected = snapshot(path.join(sourceDir, id));
      const actual = snapshot(path.join(targetRoot, id));

      for (const [rel, content] of expected) {
        if (!actual.has(rel)) drift.push(`missing: ${plugin}/skills/${id}/${rel}`);
        else if (actual.get(rel) !== content) drift.push(`stale: ${plugin}/skills/${id}/${rel}`);
      }
      for (const rel of actual.keys()) {
        if (!expected.has(rel)) drift.push(`extra: ${plugin}/skills/${id}/${rel}`);
      }
    }

    if (fs.existsSync(targetRoot)) {
      const owned = new Set(ids);
      for (const entry of fs.readdirSync(targetRoot, { withFileTypes: true })) {
        if (entry.isDirectory() && !owned.has(entry.name)) {
          drift.push(`orphan: ${plugin}/skills/${entry.name}`);
        }
      }
    }
  }

  // Version check covers every plugin dir, including ones with no skills payload.
  for (const manifestPath of listPluginManifests(pluginsDir)) {
    const declared = readManifestVersion(fs.readFileSync(manifestPath, "utf8"));
    if (declared !== version) {
      const rel = path.relative(pluginsDir, manifestPath).split(path.sep).join("/");
      drift.push(`version: ${rel} declares ${declared ?? "nothing"}, package.json is ${version}`);
    }
  }

  return { unrouted, drift, byPlugin };
}

/**
 * Writes the plugin payloads from `skills/`, pruning orphan skill directories.
 *
 * @param {object} [options]
 * @param {string} [options.sourceDir]
 * @param {string} [options.pluginsDir]
 * @param {string} [options.version] - version stamped into every plugin manifest
 * @returns {{ written: number, pruned: string[], stamped: string[] }}
 */
export function applySync({
  sourceDir = SOURCE_DIR,
  pluginsDir = PLUGINS_DIR,
  version = readPackageVersion(),
} = {}) {
  const { unrouted, byPlugin } = planSync({ sourceDir, pluginsDir, version });
  if (unrouted.length > 0) {
    throw new Error(
      `no plugin route for skill(s): ${unrouted.join(", ")} — add a rule to PLUGIN_ROUTES`
    );
  }

  let written = 0;
  /** @type {string[]} */
  const pruned = [];
  /** @type {string[]} */
  const stamped = [];

  for (const manifestPath of listPluginManifests(pluginsDir)) {
    const before = fs.readFileSync(manifestPath, "utf8");
    const after = stampVersion(before, version);
    if (after !== before) {
      fs.writeFileSync(manifestPath, after);
      stamped.push(path.relative(pluginsDir, manifestPath).split(path.sep).join("/"));
    }
  }

  for (const [plugin, ids] of byPlugin) {
    const targetRoot = path.join(pluginsDir, plugin, "skills");
    fs.mkdirSync(targetRoot, { recursive: true });

    const owned = new Set(ids);
    for (const entry of fs.readdirSync(targetRoot, { withFileTypes: true })) {
      if (entry.isDirectory() && !owned.has(entry.name)) {
        fs.rmSync(path.join(targetRoot, entry.name), { recursive: true, force: true });
        pruned.push(`${plugin}/skills/${entry.name}`);
      }
    }

    for (const id of ids) {
      const dest = path.join(targetRoot, id);
      fs.rmSync(dest, { recursive: true, force: true });
      fs.cpSync(path.join(sourceDir, id), dest, { recursive: true });
      written += 1;
    }
  }

  return { written, pruned, stamped };
}

function main() {
  const checkOnly = process.argv.includes("--check");

  if (checkOnly) {
    const { unrouted, drift } = planSync();
    if (unrouted.length === 0 && drift.length === 0) {
      console.log("✅ plugin payloads are in sync with skills/ and package.json");
      return;
    }
    for (const id of unrouted) {
      console.error(`❌ skill "${id}" matches no PLUGIN_ROUTES rule`);
    }
    for (const line of drift) {
      console.error(`❌ ${line}`);
    }
    console.error("\nRun: npm run sync:plugin-skills");
    process.exitCode = 1;
    return;
  }

  const { written, pruned, stamped } = applySync();
  console.log(`✅ synced ${written} skill(s) into plugins/`);
  for (const dir of pruned) {
    console.log(`   pruned ${dir}`);
  }
  for (const manifest of stamped) {
    console.log(`   stamped version in ${manifest}`);
  }
}

if (import.meta.url === pathToFileURL(process.argv[1]).href) {
  main();
}
